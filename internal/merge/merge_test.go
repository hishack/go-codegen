func tmpFile(t *testing.T, name, content string) string {
	t.Helper()
	p := filepath.Join(t.TempDir(), name)
	if content != "" {
		if err := os.WriteFile(p, []byte(content), 0o644); err != nil {
			t.Fatal(err)
		}
	}
	return p
}

func mustRender(t *testing.T, f *File) string {
	t.Helper()
	out, changed, err := f.Render()
	if err != nil {
		t.Fatalf("Render: %v", err)
	}
	if !changed {
		t.Fatal("期望有变更,实际没有")
	}
	if err := os.WriteFile(f.path, out, 0o644); err != nil {
		t.Fatal(err)
	}
	return string(out)
}

// TestNewFile 从零生成完整文件
func TestNewFile(t *testing.T) {
	p := tmpFile(t, "user.go", "")
	f, err := Load(p)
	if err != nil {
		t.Fatal(err)
	}
	f.SetPackage("handler")
	f.SetHeader("Code generated by go-codegen. DO NOT EDIT.")
	f.NeedImports("context", "strconv", "github.com/cloudwego/hertz/pkg/app")

	if _, err := f.UpsertType("type UserHandler struct {\n\tsvc service.IUserService\n}", PolicyAlways); err != nil {
		t.Fatal(err)
	}
	if _, err := f.UpsertFunc("*UserHandler", "GetUser",
		"// GetUser 获取用户\nfunc (u *UserHandler) GetUser(ctx context.Context, id int64) error {\n\treturn nil\n}", PolicyAlways); err != nil {
		t.Fatal(err)
	}

	out := mustRender(t, f)
	for _, want := range []string{
		"// Code generated by go-codegen. DO NOT EDIT.",
		"package handler",
		`"context"`,
		`"strconv"`,
		`"github.com/cloudwego/hertz/pkg/app"`,
		"type UserHandler struct {",
		"func (u *UserHandler) GetUser(ctx context.Context, id int64) error {",
	} {
		if !strings.Contains(out, want) {
			t.Errorf("输出缺少 %q\n---\n%s", want, out)
		}
	}
	// 标准库 import 应排在第三方前面
	if strings.Index(out, `"context"`) > strings.Index(out, `"github.com/cloudwego/hertz/pkg/app"`) {
		t.Errorf("import 分组顺序错误:\n%s", out)
	}
}

// TestInsertPreservesUserCode 往已有文件追加声明,用户代码一字节不动
func TestInsertPreservesUserCode(t *testing.T) {
	orig := `package handler

// 用户手写的辅助函数,格式故意不太标准
func helper( s string ) string {
	return s + "!" // 手动改过
}
`
	p := tmpFile(t, "user.go", orig)
	f, _ := Load(p)
	f.NeedImports("strconv")
	if _, err := f.UpsertFunc("*UserHandler", "New", "func (u *UserHandler) New() error {\n\treturn nil\n}", PolicyAlways); err != nil {
		t.Fatal(err)
	}
	out := mustRender(t, f)

	if !strings.Contains(out, "func helper( s string ) string {") {
		t.Errorf("用户代码格式被改动了:\n%s", out)
	}
	if !strings.Contains(out, `func (u *UserHandler) New() error {`) {
		t.Errorf("新方法没有插入:\n%s", out)
	}
	if !strings.Contains(out, `"strconv"`) {
		t.Errorf("import 没有补上:\n%s", out)
	}
}

// TestIdempotent 二次合并应无任何变更
func TestIdempotent(t *testing.T) {
	p := tmpFile(t, "user.go", "")
	f, _ := Load(p)
	f.SetPackage("service")
	f.NeedImports("context")
	_, _ = f.UpsertInterfaceMethod("IUserService", "GetUser(ctx context.Context, id int64) (int64, error)")
	first := mustRender(t, f)

	f2, err := Load(p)
	if err != nil {
		t.Fatal(err)
	}
	f2.NeedImports("context")
	act, err := f2.UpsertInterfaceMethod("IUserService", "GetUser(ctx context.Context, id int64) (int64, error)")
	if err != nil {
		t.Fatal(err)
	}
	if act != ActionNone {
		t.Fatalf("第二次合并期望 ActionNone,实际 %v", act)
	}
	_, changed, err := f2.Render()
	if err != nil {
		t.Fatal(err)
	}
	if changed {
		t.Fatal("第二次合并不应有变更")
	}
	_ = first
}

// TestUpsertFuncPolicies 三种策略的行为
func TestUpsertFuncPolicies(t *testing.T) {
	orig := `package logic

// GetUser 用户手写实现
func (s *UserService) GetUser(ctx context.Context, id int64) (*model.User, error) {
	return nil, nil // 用户逻辑
}
`
	run := func(policy Policy, newText string) (string, Action) {
		p := tmpFile(t, "logic.go", orig)
		f, _ := Load(p)
		act, err := f.UpsertFunc("*UserService", "GetUser", newText, policy)
		if err != nil {
			t.Fatal(err)
		}
		// Conflict/None 意味着源码没有任何改动
		if act == ActionNone || act == ActionConflict {
			return orig, act
		}
		out, changed, err := f.Render()
		if err != nil {
			t.Fatal(err)
		}
		if !changed {
			t.Fatal("期望有变更")
		}
		return string(out), act
	}

	// 签名一致:IfAbsent/IfSigDiff 都不动用户实现(PolicyAlways 用于生成器全权的声明,见下)
	sameSig := "func (s *UserService) GetUser(ctx context.Context, id int64) (*model.User, error) {\n\treturn nil, nil\n}"
	for _, pol := range []Policy{PolicyIfAbsent, PolicyIfSigDiff} {
		out, act := run(pol, sameSig)
		if act != ActionNone {
			t.Errorf("policy=%d 签名一致期望 ActionNone,实际 %v", pol, act)
		}
		if !strings.Contains(out, "用户逻辑") {
			t.Errorf("policy=%d 用户实现被覆盖:\n%s", pol, out)
		}
	}

	// PolicyAlways 只看内容:正文不同即替换(用于路由函数/接口签名等生成器全权的代码)
	outAlways, actAlways := run(PolicyAlways, sameSig)
	if actAlways != ActionUpdated {
		t.Errorf("PolicyAlways 正文不同期望 ActionUpdated,实际 %v", actAlways)
	}
	if !strings.Contains(outAlways, "return nil, nil") || strings.Contains(outAlways, "用户手写实现") {
		t.Errorf("PolicyAlways 没有整体替换:\n%s", outAlways)
	}

	// 签名变化:PolicyIfAbsent 保留并告警;PolicyIfSigDiff 替换
	diffSig := "func (s *UserService) GetUser(ctx context.Context, id int64, name string) (*model.User, error) {\n\treturn nil, nil\n}"
	out, act := run(PolicyIfAbsent, diffSig)
	if act != ActionConflict {
		t.Errorf("PolicyIfAbsent 期望 ActionConflict,实际 %v", act)
	}
	if !strings.Contains(out, "用户逻辑") {
		t.Errorf("PolicyIfAbsent 用户实现被覆盖:\n%s", out)
	}

	out, act = run(PolicyIfSigDiff, diffSig)
	if act != ActionUpdated {
		t.Errorf("PolicyIfSigDiff 期望 ActionUpdated,实际 %v", act)
	}
	if strings.Contains(out, "用户逻辑") {
		t.Errorf("PolicyIfSigDiff 应替换为新实现:\n%s", out)
	}
}

// TestPolicyAlwaysBody 路由函数内容变化时整体替换
func TestPolicyAlwaysBody(t *testing.T) {
	orig := `package router

import "github.com/cloudwego/hertz/pkg/app/server"

// RegisterUserRoutes 注册用户路由
func RegisterUserRoutes(h *server.Hertz) {
	h.GET("/users", nil)
}
`
	p := tmpFile(t, "user_router.go", orig)
	f, _ := Load(p)
	newText := "// RegisterUserRoutes 注册用户路由\nfunc RegisterUserRoutes(h *server.Hertz) {\n\th.GET(\"/users\", nil)\n\th.POST(\"/users\", nil)\n}"
	act, err := f.UpsertFunc("", "RegisterUserRoutes", newText, PolicyAlways)
	if err != nil {
		t.Fatal(err)
	}
	if act != ActionUpdated {
		t.Fatalf("期望 ActionUpdated,实际 %v", act)
	}
	out := mustRender(t, f)
	if !strings.Contains(out, `h.POST("/users", nil)`) {
		t.Errorf("函数体没有被替换:\n%s", out)
	}
	if !strings.Contains(out, `h.GET("/users", nil)`) {
		t.Errorf("原有路由丢失:\n%s", out)
	}
}

// TestUpsertType 结构体字段变化时替换,同时保留其他类型
func TestUpsertType(t *testing.T) {
	orig := `package api

// 手写类型
type Extra struct{ A int }

// CreateUserRequest 创建用户请求
type CreateUserRequest struct {
	Name string ` + "`" + `json:"name"` + "`" + `
}
`
	p := tmpFile(t, "user.go", orig)
	f, _ := Load(p)
	newText := "// CreateUserRequest 创建用户请求\ntype CreateUserRequest struct {\n\tName string `json:\"name\" form:\"name\"`\n\tAge  int    `json:\"age\" form:\"age\"`\n}"
	act, err := f.UpsertType(newText, PolicyAlways)
	if err != nil {
		t.Fatal(err)
	}
	if act != ActionUpdated {
		t.Fatalf("期望 ActionUpdated,实际 %v", act)
	}
	out := mustRender(t, f)
	if !strings.Contains(out, "Age") {
		t.Errorf("结构体没有被替换:\n%s", out)
	}
	if !strings.Contains(out, "type Extra struct{ A int }") {
		t.Errorf("手写类型丢失:\n%s", out)
	}

	// 幂等
	f2, _ := Load(p)
	if err := os.WriteFile(p, []byte(out), 0o644); err != nil {
		t.Fatal(err)
	}
	f2, _ = Load(p)
	act, err = f2.UpsertType(newText, PolicyAlways)
	if err != nil || act != ActionNone {
		t.Fatalf("二次合并期望 ActionNone,实际 %v err=%v", act, err)
	}
}

// TestInterfaceOps 接口方法插入/替换/空接口
func TestInterfaceOps(t *testing.T) {
	orig := `package service

type IUserService interface {
	GetUser(ctx context.Context, id int64) (int64, error)
}
`
	p := tmpFile(t, "service.go", orig)
	f, _ := Load(p)

	// 插入新方法
	act, err := f.UpsertInterfaceMethod("IUserService", "CreateUser(ctx context.Context, req *api.CreateUserRequest) (int64, error)")
	if err != nil || act != ActionAdded {
		t.Fatalf("期望 ActionAdded,实际 %v err=%v", act, err)
	}
	out := mustRender(t, f)
	if !strings.Contains(out, "CreateUser(ctx context.Context, req *api.CreateUserRequest) (int64, error)") {
		t.Errorf("方法没有插入:\n%s", out)
	}
	if !strings.Contains(out, "GetUser(ctx context.Context, id int64) (int64, error)") {
		t.Errorf("原有方法丢失:\n%s", out)
	}

	// 替换签名变化的方法
	f2, _ := Load(p)
	_ = os.WriteFile(p, []byte(out), 0o644)
	f2, _ = Load(p)
	act, err = f2.UpsertInterfaceMethod("IUserService", "GetUser(ctx context.Context, id int64) (*model.User, error)")
	if err != nil || act != ActionUpdated {
		t.Fatalf("期望 ActionUpdated,实际 %v err=%v", act, err)
	}
	out2 := mustRender(t, f2)
	if !strings.Contains(out2, "(*model.User, error)") {
		t.Errorf("签名没有被替换:\n%s", out2)
	}

	// 空接口插入
	p3 := tmpFile(t, "s3.go", "package service\n\ntype IEdgeService interface{}\n")
	f3, _ := Load(p3)
	if _, err := f3.UpsertInterfaceMethod("IEdgeService", "Ping(ctx context.Context) error"); err != nil {
		t.Fatal(err)
	}
	out3 := mustRender(t, f3)
	if !strings.Contains(out3, "type IEdgeService interface {\n\tPing(ctx context.Context) error\n}") {
		t.Errorf("空接口插入失败:\n%s", out3)
	}
}

// TestImports 孤儿 import 清理:只清自己造成的
func TestImports(t *testing.T) {
	// strconv 只被被替换的 GetUser 使用,替换后应被清理;app 仍被其它函数使用,应保留
	orig := `package handler

import (
	"context"
	"strconv"

	"github.com/cloudwego/hertz/pkg/app"
)

// GetUser 旧实现(用 strconv)
func (u *UserHandler) GetUser(ctx context.Context, c *app.RequestContext) error {
	_ = strconv.Itoa(1)
	return nil
}

// 其他函数(用 app)
func other(c *app.RequestContext) {}
`
	p := tmpFile(t, "user.go", orig)
	f, _ := Load(p)
	newText := "// GetUser 新实现(不用 strconv)\nfunc (u *UserHandler) GetUser(ctx context.Context, c *app.RequestContext) error {\n\treturn nil\n}"
	if _, err := f.UpsertFunc("*UserHandler", "GetUser", newText, PolicyAlways); err != nil {
		t.Fatal(err)
	}
	out := mustRender(t, f)
	if strings.Contains(out, `"strconv"`) {
		t.Errorf("孤儿 import 没有被清理:\n%s", out)
	}
	if !strings.Contains(out, `"context"`) || !strings.Contains(out, `"github.com/cloudwego/hertz/pkg/app"`) {
		t.Errorf("还在使用的 import 被误删:\n%s", out)
	}

	// 原本就没用到的 import 不动(用户自己的问题)
	orig2 := "package a\n\nimport \"fmt\"\n\nfunc x() {}\n"
	p2 := tmpFile(t, "a.go", orig2)
	f2, _ := Load(p2)
	if _, err := f2.UpsertFunc("", "y", "func y() {}", PolicyAlways); err != nil {
		t.Fatal(err)
	}
	out2 := mustRender(t, f2)
	if !strings.Contains(out2, `"fmt"`) {
		t.Errorf("原本未使用的 import 不应被删:\n%s", out2)
	}
}

