// Package merge 提供"增量写入 Go 源文件"的能力。
//
// 核心思路是文本拼接而不是 AST 重新打印:
// 先解析现有文件拿到每个声明的字节区间,生成器声明"插入/替换"意图,
// 最后按位置从后往前对原始源码做切割拼接。
// 这样没被触碰的用户代码(包括注释、格式、空行)保证一字节不变。
package merge

import (
	"bytes"
	"fmt"
	"go/ast"
	"go/format"
	"go/parser"
	"go/printer"
	"go/token"
	"os"
	"path/filepath"
	"sort"
	"strconv"
	"strings"
)

// Policy 决定目标声明已存在时的处理策略
type Policy int

const (
	// PolicyIfAbsent 已存在就跳过,签名不一致也不动 —— 用于 logic 等用户写业务逻辑的方法
	PolicyIfAbsent Policy = iota
	// PolicyIfSigDiff 签名不一致才替换,签名一致保留现有实现 —— 用于 handler 方法等生成的胶水代码
	PolicyIfSigDiff
	// PolicyAlways 内容不一致就整体替换 —— 用于路由函数、接口方法签名、生成器全权的结构体
	PolicyAlways
)

// Action 描述一次 upsert 的结果
type Action int

const (
	ActionNone     Action = iota // 内容已一致,无需改动
	ActionAdded                  // 新插入
	ActionUpdated                // 已替换
	ActionConflict               // 已存在且签名不一致,按策略保留了用户代码
)

func (a Action) String() string {
	switch a {
	case ActionAdded:
		return "added"
	case ActionUpdated:
		return "updated"
	case ActionConflict:
		return "conflict"
	}
	return "none"
}

// op 一次源码修改:把 [pos,end) 区间替换为 text(end==pos 表示纯插入)
type op struct {
	pos, end int
	text     string
}

// File 一个 Go 源文件的增量合并器
type File struct {
	path   string
	src    []byte
	fset   *token.FileSet
	file   *ast.File
	exists bool

	pkg       string            // 包名(新建文件时必须先调用 SetPackage)
	module    string            // 目标工程 module 名,新建文件时用于 import 分组
	header    []string          // 新建文件时写在 package 之前的注释行
	appendBuf []string          // 追加到文件末尾的声明
	ifaceBuf  []ifaceBufEntry   // 新建文件时收集的接口方法,渲染时组装成接口
	ifaceIdx  map[string]int    // 接口名 -> ifaceBuf 下标,保持插入顺序
	ops       []op              // 替换/插入操作
	needImps  map[string]string // path -> 别名("" 表示无别名)
	warnings  []string
}

// ifaceBufEntry 新建文件时一个待组装的接口
type ifaceBufEntry struct {
	name string
	sigs []string
}

// Load 打开一个待合并的文件。文件不存在(或为空文件)时返回 exists=false 的合并器,
// 之后照常调用 SetPackage / UpsertType / UpsertFunc,Render 会生成全新文件。
func Load(path string) (*File, error) {
	f := &File{path: path, needImps: map[string]string{}, ifaceIdx: map[string]int{}}
	src, err := os.ReadFile(path)
	if err != nil {
		if os.IsNotExist(err) {
			return f, nil
		}
		return nil, err
	}
	if strings.TrimSpace(string(src)) == "" {
		return f, nil // 空文件按新建处理
	}
	fset := token.NewFileSet()
	af, err := parser.ParseFile(fset, path, src, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil {
		return nil, fmt.Errorf("%s: 不是合法的 Go 源文件,拒绝合并: %w", filepath.Base(path), err)
	}
	f.src = src
	f.fset = fset
	f.file = af
	f.exists = true
	f.pkg = af.Name.Name
	return f, nil
}

func (f *File) Exists() bool       { return f.exists }
func (f *File) Path() string       { return f.path }
func (f *File) Warnings() []string { return f.warnings }

// SetPackage 设置包名(仅对新建文件生效)
func (f *File) SetPackage(pkg string) { f.pkg = pkg }

// SetModule 设置目标工程 module 名(仅影响新建文件的 import 分组)
func (f *File) SetModule(module string) { f.module = module }

// SetHeader 设置新建文件头部的注释行(如 "Code generated by ... DO NOT EDIT.")
func (f *File) SetHeader(lines ...string) { f.header = append(f.header, lines...) }

// NeedImports 登记插入代码所需的 import 路径,Render 时统一补进 import 块
func (f *File) NeedImports(paths ...string) {
	for _, p := range paths {
		if p != "" {
			f.needImps[p] = ""
		}
	}
}

// NeedAliasedImport 登记需要别名的 import,如 res "xxx/model/gen/response"
func (f *File) NeedAliasedImport(alias, path string) {
	if path != "" {
		f.needImps[path] = alias
	}
}

// ============ 类型声明 ============

// UpsertType 插入或替换一个顶层类型声明(完整文本,如 "type Foo struct {\n...\n}")。
// policy=PolicyAlways 时内容不一致整体替换(生成器全权的结构体);
// policy=PolicyIfAbsent 时已存在就跳过(如 logic 里用户加过依赖字段的结构体)
func (f *File) UpsertType(text string, policy Policy) (Action, error) {
	text = strings.TrimRight(strings.TrimSpace(text), "\n") + "\n"
	name, err := declaredTypeName(text)
	if err != nil {
		return ActionNone, err
	}

	if !f.exists {
		f.appendBuf = append(f.appendBuf, text)
		return ActionAdded, nil
	}

	gd, spec := f.findTypeDecl(name)
	if gd == nil {
		f.appendBuf = append(f.appendBuf, text)
		return ActionAdded, nil
	}

	if policy == PolicyIfAbsent {
		return ActionNone, nil
	}

	start, end := f.declRange(gd, spec)
	if f.normalized(start, end) == normalizeDecl(text) {
		return ActionNone, nil
	}
	f.ops = append(f.ops, op{pos: start, end: f.skipTrailingBlank(end), text: text})
	return ActionUpdated, nil
}

// ============ 函数/方法 ============

// UpsertFunc 插入或替换一个函数/方法(完整文本,含文档注释)。
// recv 是接收者类型名,如 "UserHandler"(值接收者)或 "*UserHandler"(指针接收者),普通函数传 ""。
func (f *File) UpsertFunc(recv, name, text string, policy Policy) (Action, error) {
	text = strings.TrimRight(strings.TrimSpace(text), "\n") + "\n"

	if !f.exists {
		f.appendBuf = append(f.appendBuf, text)
		return ActionAdded, nil
	}

	fd := f.findFunc(recv, name)
	if fd == nil {
		f.appendBuf = append(f.appendBuf, text)
		return ActionAdded, nil
	}

	start, end := f.funcRange(fd)
	oldSig := f.funcSigKey(fd)
	newSig, err := snippetSigKey(text)
	if err != nil {
		return ActionNone, fmt.Errorf("生成的代码无法解析(%s): %w", name, err)
	}

	switch policy {
	case PolicyIfAbsent:
		if oldSig == newSig {
			return ActionNone, nil
		}
		f.warnings = append(f.warnings,
			fmt.Sprintf("%s: 方法 %s 的签名与 yaml 定义不一致,已保留现有实现,请手动同步",
				filepath.Base(f.path), name))
		return ActionConflict, nil

	case PolicyIfSigDiff:
		if oldSig == newSig {
			return ActionNone, nil // 签名没变,实现体(可能被用户改过)原样保留
		}
		f.ops = append(f.ops, op{pos: start, end: f.skipTrailingBlank(end), text: text})
		return ActionUpdated, nil

	default: // PolicyAlways
		if f.normalized(start, end) == normalizeDecl(text) {
			return ActionNone, nil
		}
		f.ops = append(f.ops, op{pos: start, end: f.skipTrailingBlank(end), text: text})
		return ActionUpdated, nil
	}
}

// ============ 接口方法 ============

// UpsertInterfaceMethod 在指定接口中插入或替换一个方法签名。
// sigText 形如 "GetUser(ctx context.Context, id int64) (*model.User, error)"
func (f *File) UpsertInterfaceMethod(ifaceName, sigText string) (Action, error) {
	sigText = strings.TrimSpace(sigText)
	methodName := methodNameOfSig(sigText)

	if !f.exists {
		// 新文件:方法先收集起来,Render 时组装成接口定义
		if idx, ok := f.ifaceIdx[ifaceName]; ok {
			f.ifaceBuf[idx].sigs = append(f.ifaceBuf[idx].sigs, sigText)
		} else {
			f.ifaceIdx[ifaceName] = len(f.ifaceBuf)
			f.ifaceBuf = append(f.ifaceBuf, ifaceBufEntry{name: ifaceName, sigs: []string{sigText}})
		}
		return ActionAdded, nil
	}

	id := f.findInterface(ifaceName)
	if id == nil {
		return ActionNone, fmt.Errorf("接口 %s 不存在", ifaceName)
	}
	iface := id.TypeSpec.Type.(*ast.InterfaceType)

	for _, field := range iface.Methods.List {
		if len(field.Names) == 0 || field.Names[0].Name != methodName {
			continue
		}
		// 比对只用签名字符本体(不含上方注释),注释是否更新由用户自己管理
		cmpStart, cmpEnd := f.off(field.Pos()), f.off(field.End())
		if normalizeSig(string(f.src[cmpStart:cmpEnd])) == normalizeSig(sigText) {
			return ActionNone, nil
		}
		// 替换范围不含上方文档注释:用户的注释在签名替换后依然保留
		start := cmpStart
		if field.Doc != nil {
			start = f.off(field.Doc.Pos())
		}
		end := cmpEnd
		if field.Comment != nil && f.off(field.Comment.End()) > end {
			end = f.off(field.Comment.End())
		}
		f.ops = append(f.ops, op{pos: start, end: f.skipTrailingBlank(end), text: "\t" + sigText + "\n"})
		return ActionUpdated, nil
	}

	// 新方法:插到接口体末尾(右花括号所在行的行首)
	// InterfaceType 的花括号位置在 Methods.Opening / Methods.Closing 上
	openPos, closePos := iface.Methods.Opening, iface.Methods.Closing
	needRebuild := !openPos.IsValid() || !closePos.IsValid() ||
		f.fset.Position(openPos).Line == f.fset.Position(closePos).Line
	if needRebuild {
		// 空接口写在一行(type I interface{}),整体重建
		newText := fmt.Sprintf("type %s interface {\n\t%s\n}\n", ifaceName, sigText)
		start := f.off(id.GenDecl.Pos())
		if id.GenDecl.Doc != nil {
			start = f.off(id.GenDecl.Doc.Pos())
		}
		f.ops = append(f.ops, op{pos: start, end: f.skipTrailingBlank(f.off(id.GenDecl.End())), text: newText})
		return ActionUpdated, nil
	}
	lineStart := f.lineStart(f.off(closePos))
	f.ops = append(f.ops, op{pos: lineStart, end: lineStart, text: "\t" + sigText + "\n"})
	return ActionAdded, nil
}

// ============ 查询(供生成器做"删除告警"等) ============

// FuncNames 列出指定接收者的全部方法名(recv 传结构体名,带不带 * 均可;普通函数传 "")
func (f *File) FuncNames(recv string) []string {
	var out []string
	if f.file == nil {
		return out
	}
	recv = strings.TrimPrefix(recv, "*")
	for _, d := range f.file.Decls {
		fd, ok := d.(*ast.FuncDecl)
		if !ok {
			continue
		}
		if recv == "" {
			if fd.Recv == nil {
				out = append(out, fd.Name.Name)
			}
			continue
		}
		if fd.Recv == nil {
			continue
		}
		if n, ok := recvBaseName(fd.Recv.List[0].Type); ok && strings.TrimPrefix(n, "*") == recv {
			out = append(out, fd.Name.Name)
		}
	}
	return out
}

// InterfaceMethodNames 列出接口的现有方法名
func (f *File) InterfaceMethodNames(ifaceName string) []string {
	var out []string
	id := f.findInterface(ifaceName)
	if id == nil {
		return out
	}
	for _, m := range id.TypeSpec.Type.(*ast.InterfaceType).Methods.List {
		if len(m.Names) > 0 {
			out = append(out, m.Names[0].Name)
		}
	}
	return out
}

// TypeNames 列出文件里的全部顶层类型名
func (f *File) TypeNames() []string {
	var out []string
	if f.file == nil {
		return out
	}
	for _, d := range f.file.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, s := range gd.Specs {
			if ts, ok := s.(*ast.TypeSpec); ok {
				out = append(out, ts.Name.Name)
			}
		}
	}
	return out
}

// ============ 渲染 ============

// Render 输出合并后的源码;内容没有任何变化时返回 changed=false。
func (f *File) Render() ([]byte, bool, error) {
	if !f.exists {
		out, err := f.renderNewFile()
		return out, err == nil, err
	}

	missingImports := f.missingImports()
	if len(f.ops) == 0 && len(f.appendBuf) == 0 && len(missingImports) == 0 {
		return nil, false, nil
	}

	out := string(f.src)

	// 追加声明:合并成一次 EOF 插入,保证相互之间空行规整
	if len(f.appendBuf) > 0 {
		base := strings.TrimRight(out, "\n\t ")
		out = base + "\n\n" + strings.Join(f.appendBuf, "\n")
	}

	// 替换/插入:按起点从后往前应用,前面的位置不受影响
	ops := append([]op(nil), f.ops...)
	sort.SliceStable(ops, func(i, j int) bool { return ops[i].pos > ops[j].pos })
	for _, o := range ops {
		if o.pos > len(out) || o.end > len(out) {
			return nil, false, fmt.Errorf("%s: 内部错误,替换区间越界", f.path)
		}
		out = out[:o.pos] + o.text + out[o.end:]
	}

	// import 修补:补缺失的,清掉因替换而失去引用的
	outBytes, err := f.fixImports([]byte(out), missingImports)
	if err != nil {
		return nil, false, err
	}

	// 结果必须仍能解析,防止拼接产生坏代码
	fset := token.NewFileSet()
	if _, err := parser.ParseFile(fset, f.path, outBytes, parser.SkipObjectResolution); err != nil {
		return nil, false, fmt.Errorf("%s: 合并后的代码无法解析: %w", filepath.Base(f.path), err)
	}
	return outBytes, true, nil
}

// renderNewFile 生成全新文件:头部注释 + package + import + 全部声明
func (f *File) renderNewFile() ([]byte, error) {
	if f.pkg == "" {
		return nil, fmt.Errorf("%s: 新建文件缺少包名", f.path)
	}
	var b strings.Builder
	for _, h := range f.header {
		b.WriteString("// " + strings.TrimPrefix(h, "// ") + "\n")
	}
	b.WriteString("package " + f.pkg + "\n")

	if len(f.needImps) > 0 {
		b.WriteString("\n" + importBlock(f.groupedImports()) + "\n")
	}
	for _, d := range f.appendBuf {
		b.WriteString("\n" + strings.TrimRight(d, "\n") + "\n")
	}
	for _, ifc := range f.ifaceBuf {
		b.WriteString("\ntype " + ifc.name + " interface {\n")
		for _, sig := range ifc.sigs {
			b.WriteString("\t" + sig + "\n")
		}
		b.WriteString("}\n")
	}

	formatted, err := format.Source([]byte(b.String()))
	if err != nil {
		return nil, fmt.Errorf("%s: 新文件格式化失败: %w", f.path, err)
	}
	return formatted, nil
}

// ============ import 修补 ============

// missingImports 返回登记了但文件里还没有的 import 路径
func (f *File) missingImports() []string {
	var missing []string
	if len(f.needImps) == 0 {
		return missing
	}
	existing := map[string]bool{}
	for _, s := range allImportSpecs(f.file) {
		existing[importPathOf(s)] = true
	}
	for p := range f.needImps {
		if !existing[p] {
			missing = append(missing, p)
		}
	}
	sort.Strings(missing)
	return missing
}

// importLine 按"别名 路径"格式渲染一行 import
func importLine(alias, path string) string {
	if alias != "" {
		return alias + " " + strconv.Quote(path)
	}
	return strconv.Quote(path)
}

// fixImports 补上缺失的 import,并删除"原本有引用、合并后失去引用"的孤儿 import。
// 只删自己造成的孤儿:原本就无引用的 import(用户自己的问题)一律不碰,避免误删。
func (f *File) fixImports(out []byte, missing []string) ([]byte, error) {
	fset := token.NewFileSet()
	af, err := parser.ParseFile(fset, f.path, out, parser.ParseComments|parser.SkipObjectResolution)
	if err != nil {
		return nil, fmt.Errorf("%s: import 修补前解析失败: %w", filepath.Base(f.path), err)
	}

	specs := allImportSpecs(af)
	used := usedPackageNames(af)
	usedOrig := usedPackageNames(f.file)

	// 1. 已存在的 import 若别名与需要的不一致,提醒(插入的代码按登记的别名引用)
	for _, s := range specs {
		p := importPathOf(s)
		want, ok := f.needImps[p]
		if !ok {
			continue
		}
		got := ""
		if s.Name != nil {
			got = s.Name.Name
		}
		if got != want && got != "_" && got != "." {
			f.warnings = append(f.warnings, fmt.Sprintf(
				"%s: import %q 现有别名 %q 与生成代码需要的 %q 不一致,请检查",
				filepath.Base(f.path), p, got, want))
		}
	}

	// 2. 找出孤儿(本次替换导致的)
	var orphans = map[string]bool{}
	for _, s := range specs {
		p := importPathOf(s)
		if s.Name != nil && (s.Name.Name == "_" || s.Name.Name == ".") {
			continue
		}
		name := pkgNameOf(p)
		if s.Name != nil {
			name = s.Name.Name
		}
		if used[name] || orphans[p] {
			continue
		}
		// 原文件里确实用过它、现在没了 → 是本次替换造成的,可删
		if usedOrig[name] {
			orphans[p] = true
		}
	}

	if len(missing) == 0 && len(orphans) == 0 {
		return out, nil
	}

	// 3. 重建 import(保留原有顺序,缺失的追加到末尾)
	var kept []string
	for _, s := range specs {
		p := importPathOf(s)
		if orphans[p] {
			continue
		}
		kept = append(kept, importLineOf(s))
	}
	for _, p := range missing {
		kept = append(kept, importLine(f.needImps[p], p))
	}
	return replaceImportDecls(out, fset, af, kept), nil
}

// replaceImportDecls 把文件里全部 import 声明整理为一个 import 块
func replaceImportDecls(src []byte, fset *token.FileSet, af *ast.File, lines []string) []byte {
	s := string(src)

	type rng struct{ start, end int }
	var ranges []rng
	for _, d := range af.Decls {
		if gd, ok := d.(*ast.GenDecl); ok && gd.Tok == token.IMPORT {
			start := fset.Position(gd.Pos()).Offset
			if gd.Doc != nil {
				start = fset.Position(gd.Doc.Pos()).Offset
			}
			ranges = append(ranges, rng{start, fset.Position(gd.End()).Offset})
		}
	}

	if len(lines) == 0 {
		for i := len(ranges) - 1; i >= 0; i-- {
			r := ranges[i]
			s = s[:r.start] + s[r.end:]
		}
		return []byte(strings.TrimRight(s, "\n") + "\n")
	}

	block := importBlock(lines)
	if len(lines) == 1 {
		block = "import " + lines[0]
	}

	if len(ranges) == 0 {
		// 没有 import 块:插到 package 行之后
		pkgEnd := fset.Position(af.Name.End()).Offset
		s = s[:pkgEnd] + "\n\n" + block + s[pkgEnd:]
		return []byte(s)
	}

	first := ranges[0]
	s = s[:first.start] + block + s[first.end:]
	for i := len(ranges) - 1; i >= 1; i-- {
		r := ranges[i]
		s = s[:r.start] + s[r.end:]
	}
	return []byte(s)
}

// ============ AST 查找辅助 ============

func (f *File) findFunc(recv, name string) *ast.FuncDecl {
	if f.file == nil {
		return nil
	}
	recv = strings.TrimPrefix(recv, "*")
	for _, d := range f.file.Decls {
		fd, ok := d.(*ast.FuncDecl)
		if !ok || fd.Name.Name != name {
			continue
		}
		if recv == "" {
			if fd.Recv == nil {
				return fd
			}
			continue
		}
		if fd.Recv == nil {
			continue
		}
		if n, ok := recvBaseName(fd.Recv.List[0].Type); ok && strings.TrimPrefix(n, "*") == recv {
			return fd
		}
	}
	return nil
}

func (f *File) findTypeDecl(name string) (*ast.GenDecl, *ast.TypeSpec) {
	if f.file == nil {
		return nil, nil
	}
	for _, d := range f.file.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE {
			continue
		}
		for _, s := range gd.Specs {
			if ts, ok := s.(*ast.TypeSpec); ok && ts.Name.Name == name {
				return gd, ts
			}
		}
	}
	return nil, nil
}

type ifaceDecl struct {
	GenDecl  *ast.GenDecl
	TypeSpec *ast.TypeSpec
}

func (f *File) findInterface(name string) *ifaceDecl {
	gd, ts := f.findTypeDecl(name)
	if ts == nil {
		return nil
	}
	if _, ok := ts.Type.(*ast.InterfaceType); !ok {
		return nil
	}
	return &ifaceDecl{GenDecl: gd, TypeSpec: ts}
}

// HasInterface 判断接口是否已存在
func (f *File) HasInterface(name string) bool {
	return f.findInterface(name) != nil
}

// ============ 区间/文本辅助 ============

// off ast 位置 -> 源码字节偏移
func (f *File) off(p token.Pos) int { return f.fset.Position(p).Offset }

func (f *File) declRange(gd *ast.GenDecl, spec *ast.TypeSpec) (int, int) {
	start := f.off(gd.Pos())
	end := f.off(gd.End())
	if len(gd.Specs) > 1 {
		// 分组声明:只替换 spec 本身
		start = f.off(spec.Pos())
		end = f.off(spec.End())
	} else if gd.Doc != nil {
		start = f.off(gd.Doc.Pos())
	}
	return start, end
}

func (f *File) funcRange(fd *ast.FuncDecl) (int, int) {
	start := f.off(fd.Pos())
	if fd.Doc != nil {
		start = f.off(fd.Doc.Pos())
	}
	return start, f.off(fd.End())
}

// fieldRange 字段区间,含上方注释与行尾注释
func (f *File) fieldRange(fl *ast.Field) (int, int) {
	start := f.off(fl.Pos())
	if fl.Doc != nil {
		start = f.off(fl.Doc.Pos())
	}
	end := f.off(fl.End())
	if fl.Comment != nil && f.off(fl.Comment.End()) > end {
		end = f.off(fl.Comment.End())
	}
	return start, end
}

// lineStart 返回 offset 所在行的行首偏移
func (f *File) lineStart(off int) int {
	i := bytes.LastIndexByte(f.src[:off], '\n')
	return i + 1
}

// skipTrailingBlank 把替换区间的末尾向后扩展,吃掉旧声明遗留的尾随空行。
//
// 背景:替换区间的 end 取自 AST 节点,不含尾随空白。当新声明比旧声明短时
// (典型场景:yaml 注释被精简),旧内容尾部会残留多余空行,产物就过不了 gofmt。
//
// 做法:从 end 起跳过所有空白,停在下一个非空白字符 i。
// 若这段空白里含换行,说明旧声明后面多出了整行空白,应连同替换区间一起删除,
// 声明之间的空行由生成文本自身保证;不含换行则不处理。
//
// 只清理"被替换声明"与后续内容之间的空白,不触碰用户手写代码本身。
func (f *File) skipTrailingBlank(end int) int {
	i := end
	for i < len(f.src) && isSpaceByte(f.src[i]) {
		i++
	}
	if i == end {
		return end // 后面紧跟非空白,没有可清理的空白
	}
	if bytes.IndexByte(f.src[end:i], '\n') >= 0 {
		return i // 整行空白,删除
	}
	return end // 只是行内空格,保留
}

// isSpaceByte 判断是否为空白字符
func isSpaceByte(c byte) bool {
	return c == ' ' || c == '\t' || c == '\r' || c == '\n'
}

// normalized 取 [start,end) 的源码并按 gofmt 规范化,用于内容比较
func (f *File) normalized(start, end int) string {
	return normalizeDecl(string(f.src[start:end]))
}

// normalizeDecl 把声明文本规范化成可比对的形式
func normalizeDecl(s string) string {
	formatted, err := format.Source([]byte(strings.TrimSpace(s) + "\n"))
	if err != nil {
		return strings.TrimSpace(s)
	}
	return string(bytes.TrimSpace(formatted))
}

// normalizeSig 把接口方法签名规范化成可比对的形式
func normalizeSig(sig string) string {
	src := "package p\ntype __i interface {\n\t" + strings.TrimSpace(sig) + "\n}\n"
	fset := token.NewFileSet()
	af, err := parser.ParseFile(fset, "sig.go", src, parser.SkipObjectResolution)
	if err != nil {
		return strings.TrimSpace(sig)
	}
	ts := af.Decls[0].(*ast.GenDecl).Specs[0].(*ast.TypeSpec)
	it := ts.Type.(*ast.InterfaceType)
	if len(it.Methods.List) == 0 {
		return ""
	}
	var buf bytes.Buffer
	if err := printer.Fprint(&buf, fset, it.Methods.List[0]); err != nil {
		return strings.TrimSpace(sig)
	}
	return buf.String()
}

// funcSigKey 提取函数签名的可比对键:接收者 + 参数类型 + 返回类型(不含参数名和函数体)
func (f *File) funcSigKey(fd *ast.FuncDecl) string {
	var b strings.Builder
	if fd.Recv != nil && len(fd.Recv.List) > 0 {
		b.WriteString(exprText(f.fset, fd.Recv.List[0].Type))
	}
	b.WriteString("|")
	for _, p := range fd.Type.Params.List {
		b.WriteString(exprText(f.fset, p.Type))
		b.WriteString(",")
	}
	b.WriteString("|")
	if fd.Type.Results != nil {
		for _, r := range fd.Type.Results.List {
			b.WriteString(exprText(f.fset, r.Type))
			b.WriteString(",")
		}
	}
	return b.String()
}

// snippetSigKey 解析函数片段并取签名键
func snippetSigKey(text string) (string, error) {
	fset := token.NewFileSet()
	af, err := parser.ParseFile(fset, "snippet.go", "package p\n"+text, parser.SkipObjectResolution)
	if err != nil {
		return "", err
	}
	for _, d := range af.Decls {
		if fd, ok := d.(*ast.FuncDecl); ok {
			mock := &File{fset: fset}
			return mock.funcSigKey(fd), nil
		}
	}
	return "", fmt.Errorf("片段中没有函数")
}

// declaredTypeName 从类型声明片段中取出类型名
func declaredTypeName(text string) (string, error) {
	fset := token.NewFileSet()
	af, err := parser.ParseFile(fset, "snippet.go", "package p\n"+text, parser.SkipObjectResolution)
	if err != nil {
		return "", fmt.Errorf("生成的类型声明无法解析: %w", err)
	}
	for _, d := range af.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.TYPE || len(gd.Specs) == 0 {
			continue
		}
		if ts, ok := gd.Specs[0].(*ast.TypeSpec); ok {
			return ts.Name.Name, nil
		}
	}
	return "", fmt.Errorf("片段中没有类型声明")
}

// methodNameOfSig 从方法签名字符串里取方法名
func methodNameOfSig(sig string) string {
	sig = strings.TrimLeft(sig, " \t")
	i := strings.IndexAny(sig, "( \t")
	if i <= 0 {
		return sig
	}
	return sig[:i]
}

// ============ import 辅助 ============

func allImportSpecs(af *ast.File) []*ast.ImportSpec {
	var out []*ast.ImportSpec
	if af == nil {
		return out
	}
	for _, d := range af.Decls {
		gd, ok := d.(*ast.GenDecl)
		if !ok || gd.Tok != token.IMPORT {
			continue
		}
		for _, s := range gd.Specs {
			if is, ok := s.(*ast.ImportSpec); ok {
				out = append(out, is)
			}
		}
	}
	return out
}

func importPathOf(s *ast.ImportSpec) string {
	v, _ := strconv.Unquote(s.Path.Value)
	return v
}

func importLineOf(s *ast.ImportSpec) string {
	if s.Name != nil {
		return s.Name.Name + " " + s.Path.Value
	}
	return s.Path.Value
}

// pkgNameOf 由 import 路径推测包名(去掉版本后缀)
func pkgNameOf(path string) string {
	seg := path
	if i := strings.LastIndex(seg, "/"); i >= 0 {
		seg = seg[i+1:]
	}
	// github.com/x/y/v2 -> y;gopkg.in/yaml.v3 -> yaml
	if strings.HasPrefix(seg, "v") && allDigits(seg[1:]) {
		parent := path[:strings.LastIndex(path, "/")]
		seg = parent[strings.LastIndex(parent, "/")+1:]
	}
	if i := strings.Index(seg, "."); i > 0 {
		seg = seg[:i]
	}
	return seg
}

func allDigits(s string) bool {
	if s == "" {
		return false
	}
	for _, c := range s {
		if c < '0' || c > '9' {
			return false
		}
	}
	return true
}

// usedPackageNames 收集文件中作为包选择器使用的标识符
func usedPackageNames(af *ast.File) map[string]bool {
	used := map[string]bool{}
	if af == nil {
		return used
	}
	ast.Inspect(af, func(n ast.Node) bool {
		if sel, ok := n.(*ast.SelectorExpr); ok {
			if id, ok := sel.X.(*ast.Ident); ok {
				used[id.Name] = true
			}
		}
		return true
	})
	return used
}

// groupedImports 新建文件的 import 分三组:标准库、本 module、第三方,组间空行
func (f *File) groupedImports() []string {
	var std, own, ext []string
	for p := range f.needImps {
		switch {
		case f.module != "" && (p == f.module || strings.HasPrefix(p, f.module+"/")):
			own = append(own, p)
		case strings.Contains(strings.SplitN(p, "/", 2)[0], "."):
			ext = append(ext, p)
		default:
			std = append(std, p)
		}
	}
	sort.Strings(std)
	sort.Strings(own)
	sort.Strings(ext)

	var lines []string
	add := func(group []string) {
		if len(group) == 0 {
			return
		}
		if len(lines) > 0 {
			lines = append(lines, "")
		}
		for _, p := range group {
			lines = append(lines, importLine(f.needImps[p], p))
		}
	}
	add(std)
	add(own)
	add(ext)
	return lines
}

// importBlock 生成格式化的 import 块文本
func importBlock(lines []string) string {
	return "import (\n" + strings.Join(lines, "\n") + "\n)"
}

// quotedImports 把 import 路径加上引号
func quotedImports(paths []string) []string {
	out := make([]string, 0, len(paths))
	for _, p := range paths {
		out = append(out, strconv.Quote(p))
	}
	return out
}

// ============ 表达式打印 ============

// nodeText 打印任意 ast 节点为源码文本
func nodeText(fset *token.FileSet, n ast.Node) string {
	var buf bytes.Buffer
	if err := printer.Fprint(&buf, fset, n); err != nil {
		return "?"
	}
	return buf.String()
}

func exprText(fset *token.FileSet, e ast.Expr) string {
	return nodeText(fset, e)
}

// recvBaseName 取接收者类型名:"*UserHandler" / "UserHandler"
func recvBaseName(e ast.Expr) (string, bool) {
	switch t := e.(type) {
	case *ast.StarExpr:
		if id, ok := t.X.(*ast.Ident); ok {
			return "*" + id.Name, true
		}
	case *ast.Ident:
		return t.Name, true
	}
	return "", false
}
