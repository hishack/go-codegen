package handler

import (
	"os"
	"path/filepath"
	"strings"

	"github.com/hishack/go-codegen/config"
	"github.com/hishack/go-codegen/internal/field"
)

// WebApiGen 生成前端 TypeScript API 文件:{domain}.ts。
// 该文件由生成器全权管理(整体重写,内容不变则不写盘):
//
//	export interface CreateUserReq { name?: string }
//	export interface CreateUserRes { id: number }
//	class UserApi {
//	  async createUser(req: CreateUserReq): Promise<ApiResp<CreateUserRes>> { ... }
//	}
//	export default new UserApi()
type WebApiGen struct {
	cfg *config.CodeGenConfig
}

func NewWebApiGen(cfg *config.CodeGenConfig) *WebApiGen { return &WebApiGen{cfg: cfg} }

func (g *WebApiGen) Name() string { return "web" }

func (g *WebApiGen) Generate(ctx *GenContext, report *Report) {
	if g.cfg.WebApiOutPath == "" {
		return // 前端目录未配置则跳过
	}
	if err := os.MkdirAll(g.cfg.WebApiOutPath, 0o755); err != nil {
		report.warn("web 生成失败: " + err.Error())
		return
	}
	for _, d := range groupDomains(ctx.Yamls) {
		content := g.renderDomain(d)
		path := filepath.Join(g.cfg.WebApiOutPath, d.Name+".ts")
		old, statErr := os.ReadFile(path)
		if statErr == nil && string(old) == content {
			continue // 幂等
		}
		if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
			report.warn("web 写入失败(" + d.Name + "): " + err.Error())
			continue
		}
		if statErr == nil {
			report.Updated++
		} else {
			report.Added++
		}
	}
}

func (g *WebApiGen) renderDomain(d *domain) string {
	var b strings.Builder
	b.WriteString("// Code generated by go-codegen. DO NOT EDIT.\n")
	b.WriteString("import axios from \"@/utils/request\";\n")
	b.WriteString("import { ApiResp } from \"@/types/api\";\n")

	for _, api := range d.Apis {
		g.writeReqTypes(&b, api)
		g.writeResTypes(&b, api)
	}

	b.WriteString("\nexport class " + d.tsClass() + " {\n")
	for _, api := range d.Apis {
		g.writeMethod(&b, d, api)
	}
	b.WriteString("}\n")
	b.WriteString("\nexport default new " + d.tsClass() + "();\n")
	return b.String()
}

// ============ 类型 ============

// tsIface 一个待渲染的 TS interface
type tsIface struct {
	Name     string
	Comment  string
	Struct   *field.Struct
	Optional bool // req 顶层字段可选
}

// collectIfaces 先收集根 interface 与全部嵌套 interface(两阶段渲染的第一阶段),
// 保证嵌套定义不会插进父 interface 的字段中间。
// 嵌套命名规则:父类型名 + 大驼峰字段名,数组元素再加 Item,
// 与 Go 侧 vo 命名一一对应,如 SearchUserResListItem
func collectIfaces(rootName, rootComment string, root *field.Struct, optional bool) []tsIface {
	var out []tsIface
	var walk func(name string, s *field.Struct, optional bool)
	walk = func(name string, s *field.Struct, optional bool) {
		out = append(out, tsIface{Name: name, Struct: s, Optional: optional})
		for _, f := range s.Fields {
			switch {
			case f.Type.Kind == field.KindStruct:
				walk(name+field.UpperFirst(f.Tag), f.Type.Struct, false)
			case f.Type.Kind == field.KindSlice && f.Type.Elem != nil && f.Type.Elem.Kind == field.KindStruct:
				walk(name+field.UpperFirst(f.Tag)+"Item", f.Type.Elem.Struct, false)
			}
		}
	}
	walk(rootName, root, optional)
	out[0].Comment = rootComment
	return out
}

// renderIfaces 渲染收集好的 interface 列表
func renderIfaces(b *strings.Builder, ifaces []tsIface) {
	for _, ifc := range ifaces {
		if ifc.Comment != "" {
			b.WriteString("/** " + ifc.Name + " " + ifc.Comment + " */\n")
		}
		b.WriteString("export interface " + ifc.Name + " {\n")
		for _, f := range ifc.Struct.Fields {
			if f.Comment != "" {
				b.WriteString("  /** " + f.Comment + " */\n")
			}
			opt := ""
			if ifc.Optional {
				opt = "?"
			}
			b.WriteString("  " + f.Tag + opt + ": " + ifaceFieldType(ifc.Name, f) + ";\n")
		}
		b.WriteString("}\n\n")
	}
}

// ifaceFieldType 字段的 TS 类型:对象/对象数组引用收集阶段登记的嵌套名
func ifaceFieldType(parent string, f *field.Field) string {
	switch {
	case f.Type.Kind == field.KindStruct:
		return parent + field.UpperFirst(f.Tag)
	case f.Type.Kind == field.KindSlice && f.Type.Elem != nil && f.Type.Elem.Kind == field.KindStruct:
		return parent + field.UpperFirst(f.Tag) + "Item[]"
	default:
		return tsType(f.Type, nil)
	}
}

func (g *WebApiGen) writeReqTypes(b *strings.Builder, api *field.Api) {
	// 无 req 且无路径参数:不需要 Req 类型
	if !api.HasReq() && len(api.Params) == 0 {
		return
	}
	rootName := api.ApiName + "Req"

	// 根 interface 手动渲染:路径参数(必填) + req 字段(可选)
	b.WriteString("/** " + rootName + " " + docComment(api) + "请求参数 */\n")
	b.WriteString("export interface " + rootName + " {\n")
	for _, p := range api.Params {
		b.WriteString("  " + p.Tag + ": " + tsType(p.Type, nil) + ";\n")
	}
	if api.HasReq() {
		for _, f := range api.Req.Fields {
			if f.Comment != "" {
				b.WriteString("  /** " + f.Comment + " */\n")
			}
			b.WriteString("  " + f.Tag + "?: " + ifaceFieldType(rootName, f) + ";\n")
		}
	}
	b.WriteString("}\n\n")

	// 嵌套 interface(跳过已被手动渲染的根)
	if api.HasReq() {
		ifaces := collectIfaces(rootName, "", api.Req, true)
		renderIfaces(b, ifaces[1:])
	}
}

func (g *WebApiGen) writeResTypes(b *strings.Builder, api *field.Api) {
	// 标量 res 直接是基础类型,不生成 interface
	if !api.HasRes() || api.ScalarRes() != nil {
		return
	}
	ifaces := collectIfaces(api.ApiName+"Res", docComment(api)+"响应数据", api.Res, false)
	renderIfaces(b, ifaces)
}

// ============ 方法 ============

func (g *WebApiGen) writeMethod(b *strings.Builder, d *domain, api *field.Api) {
	hasParams := api.HasReq() || len(api.Params) > 0
	methodName := field.LowerFirst(api.ApiName)

	b.WriteString("  /** " + docComment(api) + " */\n")
	if hasParams {
		b.WriteString("  async " + methodName + "(req: " + api.ApiName +
			"Req): Promise<ApiResp<" + g.resTs(api) + ">> {\n")
	} else {
		b.WriteString("  async " + methodName + "(): Promise<ApiResp<" + g.resTs(api) + ">> {\n")
	}

	url := api.RoutePath()
	for _, p := range api.Params {
		url = strings.ReplaceAll(url, ":"+p.Tag, "${req."+p.Tag+"}")
	}
	b.WriteString("    return axios({\n")
	b.WriteString("      url: `" + url + "`,\n")
	b.WriteString("      method: \"" + strings.ToLower(api.Method) + "\",\n")
	if hasParams {
		switch api.Method {
		case "GET", "DELETE":
			b.WriteString("      params: req,\n")
		default:
			b.WriteString("      data: req,\n")
		}
	}
	b.WriteString("    });\n")
	b.WriteString("  }\n\n")
}

// resTs 响应的 TS 类型:结构体 -> {Api}Res;标量 -> 基础类型;无 -> void
func (g *WebApiGen) resTs(api *field.Api) string {
	if t := api.ScalarRes(); t != nil {
		return tsType(t, nil)
	}
	if api.HasRes() {
		return api.ApiName + "Res"
	}
	return "void"
}
