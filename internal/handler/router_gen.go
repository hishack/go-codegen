package handler

import (
	"path/filepath"
	"strings"

	"github.com/hishack/go-codegen/config"
	"github.com/hishack/go-codegen/internal/field"
	"github.com/hishack/go-codegen/internal/merge"
)

// RouterGen 生成路由注册文件:{domain}_router.go。
// 函数体完全由 yaml 推导(生成器全权),路由列表变化时整体替换:
//
//	func RegisterUserRoutes(h *server.Hertz, userHandler *handler.UserHandler) {
//		userGroup := h.Group("")
//		{
//			userGroup.POST("/users", userHandler.CreateUser)
//		}
//	}
type RouterGen struct {
	cfg *config.CodeGenConfig
}

func NewRouterGen(cfg *config.CodeGenConfig) *RouterGen { return &RouterGen{cfg: cfg} }

func (g *RouterGen) Name() string { return "router" }

func (g *RouterGen) Generate(ctx *GenContext, report *Report) {
	for _, d := range groupDomains(ctx.Yamls) {
		path := filepath.Join(g.cfg.RouterOutPath, d.Name+"_router.go")
		f, err := mergeGoFile(path, g.cfg.Module)
		if err != nil {
			report.warn("router 生成失败(" + d.Name + "): " + err.Error())
			continue
		}
		if !f.Exists() {
			f.SetPackage(pkgNameOfDir(g.cfg.RouterOutPath, "router"))
			f.SetHeader("Code generated by go-codegen. DO NOT EDIT.",
				"Author: "+g.cfg.UserName+"  Github: "+g.cfg.Github)
		}
		f.NeedImports(g.cfg.Module+"/internal/handler",
			"github.com/cloudwego/hertz/pkg/app/server")

		a, err := f.UpsertFunc("", d.routerFunc(), g.funcText(d), merge.PolicyAlways)
		if err != nil {
			report.warn("router 生成失败(" + d.Name + "): " + err.Error())
			continue
		}
		report.add(a)
		if err := writeMerge(f, report); err != nil {
			report.warn("router 写入失败(" + d.Name + "): " + err.Error())
		}
	}
}

func (g *RouterGen) funcText(d *domain) string {
	handlerParam := field.LowerFirst(d.pascal()) + "Handler" // userHandler
	var b strings.Builder
	b.WriteString("// " + d.routerFunc() + " 注册" + d.pascal() + "模块路由(路由列表由 yaml 生成)\n")
	b.WriteString("func " + d.routerFunc() + "(h *server.Hertz, " +
		handlerParam + " *handler." + d.handlerType() + ") {\n")
	b.WriteString("\t" + d.routerGroupVar() + " := h.Group(\"\")\n")
	b.WriteString("\t{\n")
	for _, api := range d.Apis {
		b.WriteString("\t\t" + d.routerGroupVar() + "." + api.Method + "(\"" +
			api.RoutePath() + "\", " + handlerParam + "." + api.ApiName + ")\n")
	}
	b.WriteString("\t}\n")
	b.WriteString("}")
	return b.String()
}
